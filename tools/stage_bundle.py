#!/usr/bin/env python3
"""Stage only manifest-verified device files into the recovery root."""
# SPDX-License-Identifier: MIT
import argparse,json,pathlib,shutil
from recovery_image import digest

def stage(bundle,tree):
    bundle=pathlib.Path(bundle);tree=pathlib.Path(tree);manifest=json.loads((bundle/'bundle.json').read_text(encoding='utf-8'))
    target=tree/'recovery/root'
    for item in manifest['entries']:
        name=pathlib.PurePosixPath(item['path'])
        if name.is_absolute() or '..' in name.parts:raise ValueError('Unsafe bundle path')
        source=bundle/name;data=source.read_bytes()
        if digest(data)!=item['sha256']:raise ValueError('Bundle checksum mismatch: '+str(name))
        dest=target/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(data)
        if item['mode']==0o100755:dest.chmod(0o755)
    generated='# Generated by tools/stage_bundle.py; dependency order, current device binaries.\n'
    generated+='AERA_LOAD_VENDOR_MODULES := "'+' '.join(manifest['early_modules'])+'"\n'
    generated+='AERA_POST_DECRYPT_MODULES := "'+' '.join(manifest['wlan_modules'])+'"\n'
    (tree/'generated_modules.mk').write_text(generated,encoding='utf-8',newline='\n')
    (tree/'bundle-manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    return manifest

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--bundle',required=True);p.add_argument('--tree',default='device/lenovo/avr');a=p.parse_args();m=stage(a.bundle,a.tree);print('Staged',len(m['entries']),'verified files')
